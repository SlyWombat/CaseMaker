// @vitest-environment jsdom
// #1191 — THE STORE'S RE-CHECK OF A RESTORED RUN.
//
// The pure report replacement is `restoredRun1191.spec.ts`; here the store action is exercised:
// a stored program this build's verifier refuses leaves the run blocked with the finding (no Load,
// Generate is the way forward), and the programs are still build A's bytes.
import { PROGRAM_CONTEXT } from './helpers/programContext';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';

import { defaultEngraveJob } from '@/engine/cnc/engrave/defaults';
import { useEngraveJobStore } from '@/store/engraveJobStore';
import { setEngraveRunClientLoader, useEngraveRunStore } from '@/store/engraveRunStore';
import { resetShopDefaultsStore } from '@/store/shopDefaultsStore';
import { resetLocationStore } from '@/store/locationStore';
import type { EngraveRunInputs } from '@/engine/cnc/engrave/runInputs';
import type { VerifyReport } from '@/engine/cnc/verify';
import type { EngraveGenerated, EngraveProgram } from '@/workers/sim/engraveGenerate';
import { settleShopSettings } from '../tools/settledShop';

const CLEAN: VerifyReport = {
  ok: true,
  findings: [],
  stats: { lines: 1, cuttingMoves: 0, deepestZ: 0, bbox: { min: [0, 0, 0], max: [1, 1, 0] } },
};

/** Z at -2, then an X/Y rapid there: this build refuses it (rapid-too-low). */
const BAD_NC = 'G90 G21\nG1 Z-2 F100\nG0 X5 Y5\nM5\nM02\n';

const INPUTS = { job: 'job-sha-1' } as unknown as EngraveRunInputs;

function programFor(nc: string, hash = 'h-flat-1.0'): EngraveProgram {
  return {
    setupIndex: 1,
    setupId: 'setup-1',
    toolKey: 'flat-1.0',
    nc,
    verify: CLEAN,
    frameNc: null,
    frameVerify: null,
    programHash: hash,
    ...PROGRAM_CONTEXT,
    cam: null,
  } as EngraveProgram;
}

/** The stored run's two programs, by their hashes. */
function restoredWithHashes(hashes: readonly string[]): EngraveGenerated {
  return generatedWith(hashes.map((hash) => programFor('G90 G21\nM5\nM02\n', hash)));
}

function generatedWith(programs: EngraveProgram[]): EngraveGenerated {
  return {
    ok: true,
    stage: 'done',
    findings: [],
    feeds: null,
    threads: null,
    threadMachining: null,
    cam: null,
    nc: programs[0]?.nc ?? null,
    verify: programs[0]?.verify ?? null,
    frameNc: null,
    frameVerify: null,
    facingNc: null,
    facingVerify: null,
    facingToolKey: null,
    facingError: null,
    facingCam: null,
    predicted: [],
    programs,
    errors: [],
  } as unknown as EngraveGenerated;
}

beforeEach(() => {
  const job = defaultEngraveJob();
  job.toolKey = 'flat-1.0';
  useEngraveJobStore.setState({ job });
  useEngraveRunStore.getState().reset();
  resetShopDefaultsStore();
  // #1276 — the re-check waits for / refuses without the shop's settings: this spec runs with them settled.
  settleShopSettings();
  resetLocationStore();
});

afterEach(() => setEngraveRunClientLoader(null));

/** The compare's planner: a fake client whose Generate returns the given result. */
function plannerReturning(fresh: EngraveGenerated | null): void {
  setEngraveRunClientLoader(async () => ({
    engraveGenerate: async () => {
      if (fresh === null) throw new Error('the worker never answered');
      return fresh;
    },
  }) as never);
}

describe('#1191 — the store re-checks a restored run', () => {
  it('a stored program this build refuses is refused with the finding, and Load stays off', async () => {
    const generated = generatedWith([programFor(BAD_NC)]);
    useEngraveRunStore.setState({
      generated,
      inputs: INPUTS,
      phase: 'ready',
      staleSince: null,
      restoreChecking: true,
    });
    await useEngraveRunStore.getState().recheckRestoredRun({ generated, inputs: INPUTS });
    const run = useEngraveRunStore.getState();
    expect(run.phase).toBe('blocked');
    expect(run.error).toContain("This build's verifier refused the stored program 1");
    // The bytes are still the stored ones; only the report changed.
    expect(run.generated!.programs[0]!.nc).toBe(BAD_NC);
    expect(run.generated!.programs[0]!.verify!.ok).toBe(false);
    expect(run.generated!.verify!.ok).toBe(false);
  });
});

  // #1191 field 1 — THE ORIGIN LINE SURVIVES THE RE-CHECK. The cross-build re-check runs a
  // simulate-only pass; that pass used to clear restoreNote on its way through, so the one-line
  // 'These programs were generated by build …' vanished the moment the check started.
  it('a passed re-check keeps the restored run’s origin line', async () => {
    const nc = 'G90 G21\nM5\nM02\n';
    const generated = generatedWith([programFor(nc)]);
    const note = 'These programs were generated by build 1.0.0+old on 10 Nov.';
    plannerReturning(generated);
    useEngraveRunStore.setState({
      generated,
      inputs: INPUTS,
      phase: 'ready',
      staleSince: null,
      restoreNote: note,
      restoreChecking: true,
    });
    await useEngraveRunStore.getState().recheckRestoredRun({ generated, inputs: INPUTS });
    const run = useEngraveRunStore.getState();
    expect(run.restoreNote).toBe(note);
    // The bytes are still the stored ones: the re-check never re-planned them.
    expect(run.generated!.programs[0]!.nc).toBe(nc);
  });

describe('#1191 — a not-yet-started job may be compared, never forced', () => {
  it('an identical plan says nothing (same), and the restored run is untouched', async () => {
    const restored = restoredWithHashes(['a', 'b']);
    plannerReturning(restoredWithHashes(['a', 'b']));
    useEngraveRunStore.setState({ generated: restored, staleSince: null, phase: 'ready' });
    await useEngraveRunStore.getState().compareRestoredPlan();
    const run = useEngraveRunStore.getState();
    expect(run.buildCompare).toEqual({ status: 'same', changed: 0, total: 2 });
    // The stored result is the same object: a comparison never replaces the plan.
    expect(run.generated).toBe(restored);
  });

  it('a different plan is an offer with the changed count, and keeping drops it', async () => {
    const restored = restoredWithHashes(['a', 'b']);
    plannerReturning(restoredWithHashes(['a', 'c']));
    useEngraveRunStore.setState({ generated: restored, staleSince: null, phase: 'ready' });
    await useEngraveRunStore.getState().compareRestoredPlan();
    expect(useEngraveRunStore.getState().buildCompare).toEqual({
      status: 'different',
      changed: 2,
      total: 2,
    });
    expect(useEngraveRunStore.getState().generated).toBe(restored);
    // Keep is the default: the offer goes, the programs stay.
    useEngraveRunStore.getState().keepRestoredPlan();
    expect(useEngraveRunStore.getState().buildCompare!.status).toBe('kept');
    expect(useEngraveRunStore.getState().generated).toBe(restored);
  });

  it('a comparison that cannot run says nothing, and does not ask again', async () => {
    const restored = restoredWithHashes(['a', 'b']);
    plannerReturning(null);
    useEngraveRunStore.setState({ generated: restored, staleSince: null, phase: 'ready' });
    await useEngraveRunStore.getState().compareRestoredPlan();
    expect(useEngraveRunStore.getState().buildCompare!.status).toBe('kept');
  });

  it('a stale run is not compared (it is not the job on screen)', async () => {
    const restored = restoredWithHashes(['a', 'b']);
    plannerReturning(restoredWithHashes(['a', 'c']));
    useEngraveRunStore.setState({ generated: restored, staleSince: Date.now(), phase: 'blocked' });
    await useEngraveRunStore.getState().compareRestoredPlan();
    expect(useEngraveRunStore.getState().buildCompare).toBeNull();
  });
});
