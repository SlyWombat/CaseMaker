import type { JSX } from 'react';
import { createPortal } from 'react-dom';
import {
  runSheetDiagramSvg,
  runSheetStackUpSvg,
  type RunSheet,
  type RunSheetFile,
  type RunSheetStep,
} from '@/engine/cnc/engrave/runSheet';
import { ProbeFitDiagram } from '@/components/ui/ProbeFitDiagram';
import './runSheet.css';

/**
 * Renders an operator run sheet (#207) — the printable, job-specific checklist `buildRunSheet`
 * produces. It is a plain renderer: no state, no stores, no fetching. The sheet data is passed
 * in; the caller decides which generated job it belongs to.
 *
 * The overlay is PORTALED to `document.body`. The panel that mounts it lives in the context
 * rail, which is a `position: fixed` drawer with a `transform` below 1024 px (#93 Phase 4a;
 * the breakpoint moved from 1366 in #355); a
 * transformed ancestor would otherwise become the containing block for this overlay's fixed
 * position and trap the sheet inside a 360 px column. A portal keeps the sheet full-page on
 * screen and, more importantly, keeps the print preview a page rather than a drawer.
 *
 * EVERY `unverified` STEP SHOWS ITS TAG. An operator must be able to tell a confirmed step from an
 * assumption, so the marker is rendered from the data, never left to prose.
 */

/**
 * #505 — the visible note says the operator's fact, and so does the hover: a printed sheet is read
 * at the bench, where an issue number is bookkeeping for someone else. #690 took the tracker
 * reference off the `title` too; it stays in the step's data (`step.unverified`), where it belongs.
 */
function unverifiedNote(): string {
  return 'Not yet confirmed on the machine.';
}

function StepBody({ step }: { step: RunSheetStep }): JSX.Element {
  return (
    <>
      <span className="run-sheet-step-text">{step.text}</span>
      {step.value !== undefined && <b className="run-sheet-step-value">{step.value}</b>}
      {step.code !== undefined && <code className="run-sheet-step-code">{step.code}</code>}
      {step.probeFit !== undefined && (
        <div className="run-sheet-diagram run-sheet-probe-fit" data-testid="run-sheet-probe-fit">
          <ProbeFitDiagram size="print" instrument={step.probeFit} testId="run-sheet-probe-fit-diagram" />
        </div>
      )}
      {step.record !== undefined && (
        <span className="run-sheet-record">
          <span className="run-sheet-record-label">{step.record}</span>
          <span className="run-sheet-record-blank" aria-hidden="true" />
        </span>
      )}
      {step.unverified !== undefined && (
        <em className="run-sheet-unverified" title="This step has not been walked at the machine yet.">
          {unverifiedNote()}
        </em>
      )}
    </>
  );
}

export function RunSheetView({
  sheet,
  onClose,
  onSaveProgram,
}: {
  sheet: RunSheet;
  onClose?: () => void;
  /**
   * #1093 R3 — ONE SAVE PER ROW of the run's file list, and nowhere else: the file bar offers
   * Save all for a multi-program run, so a single-program save is never the only way out. Absent
   * on a caller with no generated bytes to write; the rows then print without buttons.
   */
  onSaveProgram?: (file: RunSheetFile) => void;
}): JSX.Element {
  return createPortal(
    <div className="run-sheet-overlay" data-testid="run-sheet">
      <div className="run-sheet-toolbar">
        <button type="button" data-testid="run-sheet-print" onClick={() => window.print()}>
          Print
        </button>
        {onClose && (
          <button type="button" data-testid="run-sheet-close" onClick={onClose}>
            Close
          </button>
        )}
      </div>

      <article className="run-sheet">
        <header className="run-sheet-header">
          <h1>{sheet.header.jobName}</h1>
          <dl className="run-sheet-meta">
            <div>
              <dt>Machine</dt>
              <dd data-testid="run-sheet-machine">{sheet.header.machine}</dd>
            </div>
            {sheet.header.probe !== undefined && (
              <div>
                <dt>Probe</dt>
                <dd data-testid="run-sheet-probe">{sheet.header.probe}</dd>
              </div>
            )}
            {sheet.header.mount !== undefined && (
              <div>
                <dt>Mount</dt>
                <dd data-testid="run-sheet-mount">{sheet.header.mount}</dd>
              </div>
            )}
            {/* #513 — the bed the sheet's numbers are true about: what is mounted, the datum the
                job's registration reads with the day it was measured, and the surface under it. */}
            {sheet.header.bed !== undefined && (
              <div>
                <dt>Bed</dt>
                <dd data-testid="run-sheet-bed">{sheet.header.bed}</dd>
              </div>
            )}
            {/* #845 — which dialect the file is written in, when the machine is not a Makera: a
                GRBL machine is run from its owner's own sender. */}
            {sheet.header.dialect !== undefined && (
              <div>
                <dt>Dialect</dt>
                <dd data-testid="run-sheet-dialect">{sheet.header.dialect}</dd>
              </div>
            )}
            <div>
              <dt>Generated</dt>
              <dd>{sheet.header.generatedOn}</dd>
            </div>
            <div>
              <dt>File</dt>
              <dd>{sheet.header.fileName}</dd>
            </div>
            <div>
              <dt>Hash</dt>
              <dd>{sheet.header.fileHash}</dd>
            </div>
            <div>
              <dt>Estimated cycle time</dt>
              <dd>
                {sheet.header.estimatedTime} <em>({sheet.header.estimatedTimeNote})</em>
              </dd>
            </div>
          </dl>
        </header>

        {/* #1093 R3 — THE RUN'S FILES, in cut order, under the header: each row is one program's
            file (and its frame), with its own Save. A one-program run has no list — its one file
            is the header's and the file bar's Save. The buttons are screen-only (runSheet.css
            hides them in print); the names print, because the bench reads them. */}
        {sheet.files !== undefined && (
          <section className="run-sheet-files" data-testid="run-sheet-files">
            <h2>The run’s files</h2>
            <ol className="run-sheet-steps">
              {sheet.files.map((file) => (
                <li key={file.number} className="run-sheet-step" data-testid={`run-sheet-file-${file.number}`}>
                  <span className="run-sheet-step-text">
                    Program {file.number} is {file.name}
                    {file.frameName === null ? '' : `, with its frame ${file.frameName}`} — setup{' '}
                    {file.setupIndex}, cut with {file.cutter}.
                  </span>
                  {onSaveProgram !== undefined && (
                    <button
                      type="button"
                      className="run-sheet-save"
                      data-testid={`run-sheet-save-${file.number}`}
                      title={`Save ${file.name}${file.frameName === null ? '' : ` and ${file.frameName}`} to carry to the machine.`}
                      onClick={() => onSaveProgram(file)}
                    >
                      Save
                    </button>
                  )}
                </li>
              ))}
            </ol>
          </section>
        )}

        {sheet.sections.map((section) => (
          <section key={section.id} className="run-sheet-section" data-section-id={section.id}>
            <h2>{section.title}</h2>
            <ol className="run-sheet-steps">
              {section.steps.map((step, i) => (
                <li
                  key={`${section.id}-${i}`}
                  className={`run-sheet-step${step.bold ? ' run-sheet-step-bold' : ''}`}
                >
                  <StepBody step={step} />
                </li>
              ))}
            </ol>
            {/* #1073(a) — THE FLIP DRAWING, on the page of the setup it turns: the same SVG the
                Setups row shows (`flipDiagramSvg`), so the bench and the app see one picture. */}
            {section.flipDiagramSvg !== undefined && (
              <div
                className="run-sheet-diagram run-sheet-flip"
                data-testid={`run-sheet-flip-${section.id}`}
                // Pure string output from `flipDiagramSvg`; no user HTML, only generated geometry.
                dangerouslySetInnerHTML={{ __html: section.flipDiagramSvg }}
              />
            )}
            {/* #489 — the cutter this sheet names, under the section that names it. Monochrome
                standalone SVG from the same model the app draws. */}
            {section.id === 'need' && sheet.toolProfileSvg !== undefined && (
              <div
                className="run-sheet-diagram run-sheet-tool-profile"
                data-testid="run-sheet-tool-profile"
                dangerouslySetInnerHTML={{ __html: sheet.toolProfileSvg }}
              />
            )}
            {/* The paper cannot hover, so the printed drawing carries its own key: the codes it
                draws, in order. The values are on the dimension lines already. */}
            {section.id === 'need' && sheet.toolProfileLegend !== undefined && (
              <p className="run-sheet-tool-legend" data-testid="run-sheet-tool-legend">
                {sheet.toolProfileLegend}
              </p>
            )}
            {section.id === 'origin' && (
              <div
                className="run-sheet-diagram"
                data-testid="run-sheet-diagram"
                // Pure string output from `runSheet.ts`; no user HTML, only generated geometry.
                dangerouslySetInnerHTML={{ __html: runSheetDiagramSvg(sheet.diagram) }}
              />
            )}
            {/* #213 §6 — the side view of the assembly, under the section that builds it. Present
                only when the job has sacrificial material, so a plain wood job shows one diagram. */}
            {section.id === 'load' && sheet.stackUp !== undefined && (
              <div
                className="run-sheet-diagram"
                data-testid="run-sheet-stackup"
                dangerouslySetInnerHTML={{ __html: runSheetStackUpSvg(sheet.stackUp) }}
              />
            )}
          </section>
        ))}
      </article>
    </div>,
    document.body,
  );
}
