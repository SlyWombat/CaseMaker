import { useEngraveRunStore, recheckRunInputs, type EngraveRunState } from './engraveRunStore';
import { useToolRegistryStore } from './toolRegistryStore';
import { useLocationStore } from './locationStore';
import { jobFingerprint } from '@/engine/cnc/engrave/package';
import type { EngraveRunInputs } from '@/engine/cnc/engrave/runInputs';
import type { EngraveJob } from '@/types/engraveJob';
import { dayWords } from '@/engine/cnc/engrave/restart';
import { SIMULATOR_VERSION } from '@/workers/geometry/simVersion';

/**
 * #1191 — THE RECORD'S OWN SHAPE VERSION. The restore gate is THIS, never the build id: a build
 * that can read the schema restores the job's run; one that cannot says so and asks for a
 * Generate. Bump it when `PersistedRunState` changes in a way an older reader cannot accept.
 */
export const RUN_RECORD_SCHEMA = 1;

/** The one line a cross-build restore shows: where the programs came from, and when. */
export function crossBuildNote(build: string, savedAt: string): string {
  const when = dayWords(savedAt);
  return `These programs were generated by build ${build}${when === null ? '' : ` on ${when}`}.`;
}

/** The one refusal: a stored record this build cannot read, with the reason. */
export function schemaChangedNote(found: number | null): string {
  return (
    `The stored run cannot be read by this build of the app` +
    (found === null ? '' : ` (record schema ${found}, this build reads ${RUN_RECORD_SCHEMA})`) +
    `; generate again.`
  );
}

/** The durable half of a settled run. Live fields (progress, error, simProgram, simStopped) stay out. */
export type PersistedRunState = Pick<
  EngraveRunState,
  | 'generated'
  | 'oracle'
  | 'oraclePrograms'
  | 'simDiagnostics'
  | 'simStatus'
  | 'pathOnly'
  | 'simEngine'
  | 'simGridPitchMm'
  | 'simPrograms'
  | 'runMount'
  | 'phase'
  | 'acknowledged'
  | 'acknowledgedFor'
  | 'staleSince'
  | 'staleReason'
  | 'inputs'
  | 'changedSinceLast'
  | 'previousVerdict'
  | 'lastGenerateMs'
  | 'shopSignature'
>;

export interface StoredRunRecord {
  /** The JOB SHA — one record per job; a later save replaces the former. */
  id: string;
  jobSha: string;
  /** `__APP_VERSION__` + `__BUILD_COMMIT__` of the build that generated the run. A FACT, not a key. */
  build: string;
  /** #1191 — the record shape, the restore gate. See {@link RUN_RECORD_SCHEMA}. */
  schemaVersion: number;
  /**
   * #1191 — the simulator that judged the stored programs. A difference is a GATE change: the
   * cross-build re-check is mandatory before Load (the package's own version rule, #925).
   */
  simulatorVersion: number;
  shopSignature: string;
  savedAt: string;
  state: PersistedRunState;
}

/** The store's seam; a spec supplies an in-memory map. */
export interface RunRecordIO {
  put: (record: StoredRunRecord) => Promise<void>;
  listByJob: (jobSha: string) => Promise<StoredRunRecord[]>;
}

/**
 * `unsupported` is #1191's one refusal: a stored record exists, but its schema version is one this
 * build cannot read. `restored` covers a cross-build restore too — the run is back; the store
 * re-checks it.
 */
export type RunRestoreOutcome = 'restored' | 'none' | 'unsupported' | 'busy';

export interface RestoreRunOptions {
  /** The open job. Defaults to the job store's. */
  job?: EngraveJob;
  /** Its fingerprint, when a caller already has it (the spec passes one). */
  jobSha?: string;
  build?: string;
  io?: RunRecordIO;
  /** A spec seam: the stamps the current stores would produce (see `recheckRunInputs`). */
  currentInputs?: EngraveRunInputs;
  /** False skips waiting for the house reads (the spec). */
  settle?: boolean;
  waitMs?: number;
  /** False skips the post-restore input comparison (the spec's fabricated stamps). */
  recheck?: boolean;
  /**
   * #1191 — THIS BUILD'S RE-CHECK of a stored run made by a different build: the verifier and the
   * gate over the stored bytes, then the background sweep. Injectable for the spec; the app's
   * default is the run store's own `recheckRestoredRun` (the checks, never the planner).
   */
  recheckAcrossBuilds?: (state: PersistedRunState) => void | Promise<void>;
}

const DB_NAME = 'casemaker-runs';
const STORE = 'runs';
const INDEX = 'jobSha';
/** How many stored runs to keep. A run is megabytes; ten is plenty for the bench's two jobs. */
const MAX_RECORDS = 10;

let io: RunRecordIO | null = null;

/** Test seam: replace the IndexedDB store (the app never calls this). `null` restores it. */
export function setRunRecordIO(next: RunRecordIO | null): void {
  io = next;
}

function openDatabase(): Promise<IDBDatabase> {
  if (typeof indexedDB === 'undefined') {
    return Promise.reject(new Error('IndexedDB is not available in this build'));
  }
  return new Promise((resolve, reject) => {
    const request = indexedDB.open(DB_NAME, 1);
    request.onupgradeneeded = () => {
      const db = request.result;
      if (!db.objectStoreNames.contains(STORE)) {
        const store = db.createObjectStore(STORE, { keyPath: 'id' });
        store.createIndex(INDEX, 'jobSha');
      }
    };
    request.onsuccess = () => resolve(request.result);
    request.onerror = () => reject(request.error ?? new Error('the run store could not be opened'));
  });
}

async function prune(db: IDBDatabase): Promise<void> {
  const tx = db.transaction(STORE, 'readwrite');
  const store = tx.objectStore(STORE);
  const all = await new Promise<StoredRunRecord[]>((resolve, reject) => {
    const request = store.getAll();
    request.onsuccess = () => resolve(request.result as StoredRunRecord[]);
    request.onerror = () => reject(request.error ?? new Error('the run store could not be read'));
  });
  if (all.length <= MAX_RECORDS) return;
  all.sort((a, b) => (a.savedAt < b.savedAt ? 1 : -1));
  for (const old of all.slice(MAX_RECORDS)) store.delete(old.id);
  await new Promise<void>((resolve, reject) => {
    tx.oncomplete = () => resolve();
    tx.onerror = () => reject(tx.error ?? new Error('the run store could not be pruned'));
  });
}

function indexedDbIO(): RunRecordIO {
  return {
    async put(record) {
      const db = await openDatabase();
      try {
        await new Promise<void>((resolve, reject) => {
          const tx = db.transaction(STORE, 'readwrite');
          tx.objectStore(STORE).put(record);
          tx.oncomplete = () => resolve();
          tx.onerror = () => reject(tx.error ?? new Error('the run could not be stored'));
        });
        await prune(db);
      } finally {
        db.close();
      }
    },
    async listByJob(jobSha) {
      const db = await openDatabase();
      try {
        return await new Promise<StoredRunRecord[]>((resolve, reject) => {
          const tx = db.transaction(STORE, 'readonly');
          const request = tx.objectStore(STORE).index(INDEX).getAll(jobSha);
          request.onsuccess = () => resolve(request.result as StoredRunRecord[]);
          request.onerror = () => reject(request.error ?? new Error('the stored runs could not be read'));
        });
      } finally {
        db.close();
      }
    },
  };
}

function recordIO(): RunRecordIO {
  return io ?? indexedDbIO();
}

/** `__APP_VERSION__` + `__BUILD_COMMIT__`; both are build-time constants (vite's `define`). */
export function runBuildId(): string {
  const version = typeof __APP_VERSION__ === 'string' ? __APP_VERSION__ : 'unknown';
  const commit = typeof __BUILD_COMMIT__ === 'string' && __BUILD_COMMIT__ !== '' ? __BUILD_COMMIT__ : 'unknown';
  return `${version}+${commit}`;
}

/** The durable half of a run state, as plain data ready for IndexedDB. */
export function snapshotRun(state: EngraveRunState): PersistedRunState {
  return {
    generated: state.generated,
    oracle: state.oracle,
    oraclePrograms: state.oraclePrograms,
    simDiagnostics: state.simDiagnostics,
    simStatus: state.simStatus,
    pathOnly: state.pathOnly,
    simEngine: state.simEngine,
    simGridPitchMm: state.simGridPitchMm,
    simPrograms: state.simPrograms,
    runMount: state.runMount,
    phase: state.phase,
    acknowledged: state.acknowledged,
    acknowledgedFor: state.acknowledgedFor,
    staleSince: state.staleSince,
    staleReason: state.staleReason,
    inputs: state.inputs,
    changedSinceLast: state.changedSinceLast,
    previousVerdict: state.previousVerdict,
    lastGenerateMs: state.lastGenerateMs,
    shopSignature: state.shopSignature,
  };
}

/**
 * Write the settled run now, or null when there is nothing settled to write. The key's job sha is
 * the run's own stamp (`inputs.job`), not the job as it is at save time: a job edited after
 * Generate must not lend its identity to the old program.
 */
export async function persistRunNow(
  state: EngraveRunState = useEngraveRunStore.getState(),
  target: RunRecordIO = recordIO(),
): Promise<StoredRunRecord | null> {
  if (state.generated === null || state.inputs === null || state.shopSignature === null) return null;
  if (state.phase !== 'ready' && state.phase !== 'blocked') return null;
  const record: StoredRunRecord = {
    // #1191 — ONE RECORD PER JOB: the id is the job sha, so a new build's save replaces the older
    // record rather than adding a second one the restore could choose between.
    id: state.inputs.job,
    jobSha: state.inputs.job,
    build: runBuildId(),
    schemaVersion: RUN_RECORD_SCHEMA,
    simulatorVersion: SIMULATOR_VERSION,
    shopSignature: state.shopSignature,
    savedAt: new Date().toISOString(),
    state: snapshotRun(state),
  };
  try {
    await target.put(record);
    return record;
  } catch {
    return null; // no durable copy: the next reload is the one the beforeunload warning protects
  }
}

/** True only while a reload would drop work that is not yet in durable storage. */
export function shouldWarnBeforeReload(state: Pick<EngraveRunState, 'phase' | 'generated'>): boolean {
  return state.phase === 'generating' || state.phase === 'simulating' || state.phase === 'checking';
}

/**
 * Keep the settled runs stored, and warn before a reload that would drop an in-flight one.
 * Returns the teardown (the App's effect).
 */
export function startRunPersistence(): () => void {
  let timer: ReturnType<typeof setTimeout> | null = null;
  const schedule = (): void => {
    if (timer !== null) clearTimeout(timer);
    timer = setTimeout(() => {
      timer = null;
      void persistRunNow();
    }, 150);
  };
  const unsubscribe = useEngraveRunStore.subscribe((state, prev) => {
    if (
      state.phase !== prev.phase ||
      state.generated !== prev.generated ||
      state.oracle !== prev.oracle ||
      state.simStatus !== prev.simStatus ||
      state.acknowledgedFor !== prev.acknowledgedFor ||
      state.staleSince !== prev.staleSince ||
      state.shopSignature !== prev.shopSignature
    ) {
      schedule();
    }
  });
  const onBeforeUnload = (event: BeforeUnloadEvent): void => {
    if (!shouldWarnBeforeReload(useEngraveRunStore.getState())) return;
    event.preventDefault();
    // The legacy contract still needs returnValue in some browsers; the string is not shown.
    event.returnValue = '';
  };
  if (typeof window !== 'undefined') window.addEventListener('beforeunload', onBeforeUnload);
  return () => {
    unsubscribe();
    if (timer !== null) clearTimeout(timer);
    if (typeof window !== 'undefined') window.removeEventListener('beforeunload', onBeforeUnload);
  };
}

/**
 * Whether the house reads the shop signature is made of have settled. A build with no service
 * settles at once (`tools: 'absent'`): there will never be a location read to wait for. True
 * means the signature is meaningful; false means it is not, and a mismatch must not be stated.
 */
function shopSettled(): boolean {
  const tools = useToolRegistryStore.getState().status;
  const location = useLocationStore.getState().status;
  if (tools === 'checking') return false;
  if (location !== 'unknown') return true;
  return tools === 'absent';
}

async function waitForShopSettled(ms: number): Promise<boolean> {
  const started = Date.now();
  while (Date.now() - started < ms) {
    if (shopSettled()) return true;
    await new Promise((resolve) => setTimeout(resolve, 100));
  }
  return shopSettled();
}

/** The one deferred recheck waiting for the house reads; cleanup when it has run. */
let deferredRecheck: (() => void) | null = null;

/**
 * #1123 review — RECHECK WHEN THE READS SETTLE. Restoring with the house still reading used to
 * skip the one-shot comparison and rely on the live watchers; but a watcher fires only on a store
 * CHANGE after the restore, so an input whose store had already settled (margins, the fitted
 * surface, a house store that answered first) was never compared. Wait for the reads, then run
 * the same comparison once. No timeout and no skip: an unsettled house keeps the run unverified
 * (`restoreChecking`), never falsely current.
 */
function deferRecheck(
  restoredInputs: EngraveRunInputs | null,
  currentInputs?: EngraveRunInputs,
  /** #1191 — what to do when THIS comparison finishes; the caller owns `restoreChecking`, which
   *  must stay true while a cross-build verifier/gate re-check is still running. */
  onDone?: () => void,
): void {
  if (deferredRecheck !== null) return;
  let unsubTool: (() => void) | null = null;
  let unsubLocation: (() => void) | null = null;
  const cleanup = (): void => {
    unsubTool?.();
    unsubLocation?.();
    deferredRecheck = null;
  };
  const run = (): void => {
    if (!shopSettled()) return;
    cleanup();
    onDone?.();
    // A new run (or another restore) replaced the restored one: nothing of ours to verify.
    if (useEngraveRunStore.getState().inputs !== restoredInputs) return;
    recheckRunInputs(currentInputs);
  };
  unsubTool = useToolRegistryStore.subscribe(run);
  unsubLocation = useLocationStore.subscribe(run);
  deferredRecheck = cleanup;
  run(); // the reads may have settled between the wait ending and this subscription
}

/**
 * Restore the stored run for the open job, after the first render. Called once at boot; a run
 * already generated in this session is never overwritten ('busy').
 */
export async function restoreOpenRun(options: RestoreRunOptions = {}): Promise<RunRestoreOutcome> {
  const run = useEngraveRunStore.getState();
  if (run.phase !== 'idle' || run.generated !== null) return 'busy';
  // Wait briefly for the reads the RECHECK compares. An unanswered house no longer blocks the
  // restore (the key is job+build): restore anyway, skip the one-shot comparison, and let the live
  // watchers judge each input as its store settles.
  const settled = options.settle === false ? true : await waitForShopSettled(options.waitMs ?? 3000);
  const job = options.job ?? useEngraveJobStore.getState().job;
  const jobSha = options.jobSha ?? jobFingerprint(job);
  const build = options.build ?? runBuildId();
  const target = options.io ?? recordIO();
  let records: StoredRunRecord[];
  try {
    records = await target.listByJob(jobSha);
  } catch {
    return 'none';
  }
  if (records.length === 0) return 'none';
  // #1191 — THE SCHEMA IS THE GATE, NEVER THE BUILD ID. A record this build can read restores,
  // whichever build made it; one it cannot is the single refusal, with its reason.
  const readable = records.filter((record) => record.schemaVersion === RUN_RECORD_SCHEMA);
  if (readable.length === 0) {
    const versions = records.map((record) => record.schemaVersion).filter((v): v is number => typeof v === 'number');
    useEngraveRunStore.setState({
      restoreNote: schemaChangedNote(versions.length === 0 ? null : Math.max(...versions)),
    });
    return 'unsupported';
  }
  // The latest run stored for the job. The shop is not consulted: the recheck below is the
  // precise test, and an ETag moved by a record write must not throw the run away.
  const record = readable.sort((a, b) => (a.savedAt < b.savedAt ? 1 : -1))[0]!;
  const crossBuild = record.build !== build;
  // #1191 — A GATE VERSION CHANGE IS ALSO A RE-CHECK. The stored sim verdicts were judged by the
  // old gate; this build must read the same bytes before Load, even if the build id somehow says
  // the same (the package's own #925 rule, applied to the run).
  const gateChanged = record.simulatorVersion !== SIMULATOR_VERSION;
  const needsRecheck = crossBuild || gateChanged;
  const inputsPending = options.recheck !== false && !settled;
  useEngraveRunStore.setState({
    ...record.state,
    progress: null,
    simProgram: null,
    error: null,
    simStopped: false,
    // #1191 — a cross-build restore says where the programs came from; the same build says nothing.
    restoreNote: crossBuild ? crossBuildNote(record.build, record.savedAt) : null,
    // Unverified until this realm's input comparison AND (across builds or gate versions) this
    // build's verifier and gate have finished (review 2026-11-09 + #1191).
    restoreChecking: needsRecheck || inputsPending,
  });
  let inputDone = options.recheck === false;
  let buildDone = !needsRecheck;
  const finish = (which: 'input' | 'build'): void => {
    if (which === 'input') inputDone = true;
    else buildDone = true;
    if (inputDone && buildDone) useEngraveRunStore.setState({ restoreChecking: false });
  };
  if (options.recheck !== false) {
    if (settled) {
      recheckRunInputs(options.currentInputs);
      finish('input');
    } else {
      deferRecheck(record.state.inputs, options.currentInputs, () => finish('input'));
    }
  }
  if (needsRecheck) {
    // #1191 — THIS BUILD CHECKS THE STORED BYTES, never re-planning them: the verifier and the
    // sweep run over build A's programs; the operator's blank keeps the plan it started on.
    const recheck =
      options.recheckAcrossBuilds ??
      ((state: PersistedRunState) => useEngraveRunStore.getState().recheckRestoredRun(state));
    void Promise.resolve()
      .then(() => recheck(record.state))
      // The action leaves the run's own gate state in place when it refuses; the flag still drops
      // so the operator sees WHAT the check said rather than a spinner forever.
      .catch(() => undefined)
      .finally(() => finish('build'));
  }
  return 'restored';
}
