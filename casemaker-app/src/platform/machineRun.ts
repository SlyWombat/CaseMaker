/** The status poll's floor, ms (#386: 0.6 s faulted the controller). The shop default may only raise it. */
export const RUN_POLL_FLOOR_MS = 2000;
/** The machine's job directory — `protocol.ts`'s `GCODE_DIR`, where an upload writes. */
export const RUN_DIR = '/sd/gcodes';

export interface RunSettings {
  pollMs: number;
  noProgressMs: number;
  missLimit: number;
  /** #449 — the status poll's reply window (`run.statusReplyMs`); `STATUS_POLL_TIMING` when absent. */
  statusTiming?: ConsoleTiming;
  /** #449 — what a Stop pressed during the run polls with (`stop.*`); `STOP_FALLBACK` when absent. */
  stop?: StopSettings;
}

/** A status line read for the job's progress — `protocol.ts`'s `readJobProgress`, restated web-safe. */
export interface Progress {
  state: string | null;
  line: number | null;
  percent: number | null;
  elapsedS: number | null;
}

export function readProgress(text: string): Progress {
  const state = /^<([A-Za-z]+)/.exec(text.trim());
  const p = /(?:^|\|)P:([^|>]*)/.exec(text);
  const fields = p === null ? [] : (p[1] as string).split(',');
  const num = (i: number): number | null => {
    const raw = fields[i]?.trim();
    if (raw === undefined || raw === '') return null;
    const v = Number(raw);
    return Number.isFinite(v) ? v : null;
  };
  return { state: state === null ? null : state[1]!, line: num(0), percent: num(1), elapsedS: num(2) };
}

/** The one line that starts a program — `protocol.ts`'s `playProgramLine` rule. */
export function playLine(filename: string): string | null {
  const path = `${RUN_DIR}/${filename}`;
  return /^\/[A-Za-z0-9._/-]+$/.test(path) && !filename.includes('/') ? `play ${path}` : null;
}

export type RunEvent =
  | { kind: 'sent'; line: string; reply: string }
  | { kind: 'poll'; progress: Progress }
  | { kind: 'missed'; misses: number; detail: string }
  /** Something the run decided, said in the log the operator is reading. */
  | { kind: 'note'; text: string };

/**
 * Which vacuum words a program's text carries (#419 decision 4), when the app's upload knows and
 * says so. `whole` is a one-program job; `first`/`middle`/`last` are the shares of a multi-program
 * run; `none` is a job whose accessory output is off (`air: false`), so no word is in any file.
 *
 * The span is the JOB's, not the file's guess: a middle file carries neither word, and the runner
 * must not read that silence as "nobody owns the vacuum" and bracket it. The caller that uploaded
 * the file says which share it is; {@link RunDeps.vacuumSpan} carries the answer into the log.
 */
export type VacuumSpan = 'whole' | 'first' | 'middle' | 'last' | 'none';

/** Who switches the vacuum: this run's bracket, the program's own words, or the job's span. */
export type VacuumOwner = 'runner' | 'program' | 'job';

export type RunOutcome =
  | { kind: 'refused'; reason: string }
  | { kind: 'finished'; last: Progress; homed: boolean; vacuumOff: boolean; antistaticOff?: boolean; vacuumOwner?: VacuumOwner; span?: VacuumSpan }
  | { kind: 'aborted'; stop: StopOutcome; last: Progress }
  | { kind: 'alarm'; alarm: string; last: Progress }
  | { kind: 'unreachable'; last: Progress; misses: number }
  | { kind: 'never-started'; last: Progress; vacuumOff: boolean; antistaticOff?: boolean; vacuumOwner?: VacuumOwner; span?: VacuumSpan }
  /**
   * Stop was pressed before the machine ever reported progress, and it reads Idle: nothing here can
   * tell whether the program ran, so nothing further is sent — no `M332`, no home (#423 re-review).
   */
  | { kind: 'stopped-unconfirmed'; status: string };

export interface RunDeps {
  session: Pick<ConsoleHandle, 'send'>;
  settings: RunSettings;
  /**
   * #419 Q-E — the program text carries its own `M331`/`M332`. When true this run sends neither
   * (a bracket would undo the file's own, and a multi-file job must keep the vacuum on between
   * files). Defaults to false: a file that never says so keeps the runner's fallback bracket.
   */
  programOwnsVacuum?: boolean;
  /**
   * #419 decision 4 / #469 — this file's share of the job's vacuum span, when the upload knows it.
   * Set to `none` for an `air: false` job: the runner must send neither word, and the outcome says
   * the job runs without the vacuum rather than claiming a program switched it off. When present it
   * outranks `programOwnsVacuum` and makes the owner `job`.
   */
  vacuumSpan?: VacuumSpan;
  /**
   * #564 — switch the antistatic (static-removal) device on at the start and off at the end,
   * alongside the vacuum's own words. The caller sets it when the job's material is a plastic and
   * the machine has the device (`capabilities.antistatic`); the program never carries `M331.4` /
   * `M332.4`, so this is the ONLY thing that switches it — off exactly once per run, at the finish
   * or, on an abort, through {@link stopOnSession}.
   */
  antistatic?: boolean;
  /** True once the person pressed Stop; read at every poll boundary. */
  stopRequested: () => boolean;
  onEvent?: (e: RunEvent) => void;
  sleep?: (ms: number) => Promise<void>;
  now?: () => number;
}

/**
 * Does this program text switch the vacuum itself? The one reading the caller and the run share:
 * a LINE whose first word is `M331`/`M332` means its generator owns the vacuum span (#419's post
 * writes exactly that, one word on its own line). A word inside a comment does not count — a false
 * "yes" would leave the vacuum off for the whole cut, which is the one mistake worth avoiding.
 */
export function programOwnsVacuum(nc: string | null | undefined): boolean {
  return typeof nc === 'string' && /^[ \t]*M33[12]\b/im.test(nc);
}

const realSleep = (ms: number) => new Promise<void>((resolve) => setTimeout(resolve, ms));

function said(r: ConsoleSendResult): string {
  return r.kind === 'sent' || r.kind === 'timeout' ? r.text : r.detail;
}

function anyAlarm(r: ConsoleSendResult): string | null {
  if (r.kind !== 'sent' && r.kind !== 'timeout') return null;
  return alarmLine(r.text) ?? alarmLine(r.carried?.text ?? null);
}

export async function runProgram(filename: string, deps: RunDeps): Promise<RunOutcome> {
  const sleep = deps.sleep ?? realSleep;
  const now = deps.now ?? (() => Date.now());
  const pollMs = Math.max(RUN_POLL_FLOOR_MS, deps.settings.pollMs);
  /** Every line goes through here, Stop's included, so the panel sees all of them. */
  const send = async (line: string, timing?: Partial<ConsoleTiming>): Promise<ConsoleSendResult> => {
    const r = await deps.session.send(line, timing);
    deps.onEvent?.({ kind: 'sent', line, reply: said(r) });
    return r;
  };
  const statusTiming = deps.settings.statusTiming ?? STATUS_POLL_TIMING;
  const poll = () => send('?', statusTiming);

  const play = playLine(filename);
  if (play === null) return { kind: 'refused', reason: `${filename} is not a file name the machine can play` };

  // 1 — Idle with no alarm and no program in progress, or nothing.
  const before = await poll();
  const alarmBefore = anyAlarm(before);
  if (alarmBefore !== null) return { kind: 'refused', reason: `the controller is in an alarm (\`${alarmBefore}\`); nothing was played — clear it at the machine` };
  if (before.kind !== 'sent') return { kind: 'refused', reason: 'the machine did not answer a status poll, so whether it is idle is unknown; nothing was played' };
  const pre = readProgress(before.text);
  if (pre.state !== 'Idle') return { kind: 'refused', reason: `the controller reports ${pre.state ?? 'no state'}, not Idle; nothing was played` };
  // Idle with P below 100 is a program paused mid-job (the 3–4 s `Idle` at `M05`), not a free machine.
  if (pre.percent !== null && pre.percent < 100) {
    return { kind: 'refused', reason: `the controller reads Idle with a program at ${pre.percent} % — one is still in progress; nothing was played` };
  }
  if (deps.stopRequested()) return { kind: 'refused', reason: 'Stop was pressed before the program started; nothing was played' };

  // 2 — the vacuum, unless the job owns the span (#419 Q-E). A caller that does not say keeps the
  // old bracket: files posted before #419, or uploaded from elsewhere, carry none.
  const span = deps.vacuumSpan;
  const vacOwner: VacuumOwner =
    span !== undefined ? 'job' : deps.programOwnsVacuum === true ? 'program' : 'runner';
  if (vacOwner !== 'runner') {
    // Said in the log the operator is reading, so "why did no M331 appear?" has its answer there.
    deps.onEvent?.({
      kind: 'note',
      text:
        vacOwner === 'job'
          ? span === 'none'
            ? 'The job runs without the vacuum (its accessory output is off), so this run sends no M331 or M332.'
            : 'The job owns the vacuum span (M331 on its first program, M332 on its last), so this run does not bracket this file.'
          : 'The program switches the vacuum itself (M331/M332 in the file), so this run does not bracket it.',
    });
  } else {
    const vac = await send(VACUUM_ON);
    if (vac.kind !== 'sent' || anyAlarm(vac) !== null) {
      return { kind: 'refused', reason: `the vacuum did not switch on (${said(vac).trim() || vac.kind}); nothing was played` };
    }
  }

  // 2b — the antistatic, for a plastic job only (#564). Unlike the vacuum the program never carries
  // `M331.4`, so the run switches it on for EVERY file of a plastic job, whoever owns the vacuum's
  // words. A failure refuses, exactly as the vacuum's did: nothing is played on a job whose
  // accessory did not switch on, and a vacuum THIS run switched on goes off again.
  if (deps.antistatic === true) {
    const anti = await send(ANTISTATIC_ON);
    if (anti.kind !== 'sent' || anyAlarm(anti) !== null) {
      if (vacOwner === 'runner') await send(VACUUM_OFF);
      return { kind: 'refused', reason: `the antistatic did not switch on (${said(anti).trim() || anti.kind}); nothing was played` };
    }
  }

  // 3 — play. Only a reply that SAYS no, or a line that was never sent, means it did not start.
  const playSentAt = now();
  const played = await send(play);
  if (played.kind === 'sent' && /\berror\b|not found|no such file|unknown/i.test(played.text)) {
    // Nothing ran, so a runner-owned vacuum goes off again. A program-owned one never went on.
    if (vacOwner === 'runner') await send(VACUUM_OFF);
    if (deps.antistatic === true) await send(ANTISTATIC_OFF);
    return { kind: 'refused', reason: `the controller did not accept the program: ${played.text.trim()}` };
  }
  if (played.kind === 'refused' || played.kind === 'unavailable') {
    if (vacOwner === 'runner') await send(VACUUM_OFF);
    if (deps.antistatic === true) await send(ANTISTATIC_OFF);
    return { kind: 'refused', reason: `${play} could not be sent: ${said(played)}` };
  }
  // A timeout or a socket error AFTER the line went out is not a job that failed to start: the
  // controller may be running it. The watch starts anyway (the harness's rule); the next poll opens a
  // fresh connection if the old one died.

  // 4 — watch.
  let last: Progress = { state: null, line: null, percent: null, elapsedS: null };
  let seenProgress = false;
  let misses = 0;
  let lastSendAt = playSentAt;
  for (;;) {
    const wait = pollMs - (now() - lastSendAt);
    if (wait > 0) await sleep(wait);

    if (deps.stopRequested()) {
      const stop = await stopOnSession({ send }, sleep, deps.settings.stop ?? STOP_FALLBACK, deps.antistatic === true);
      // `not-running` is Idle with no program in progress. After progress was seen, that is the job
      // ending just as Stop was pressed — a finish. Before any, it proves nothing: say so, send nothing.
      if (stop.kind === 'not-running') {
        return seenProgress ? finish(readProgress(stop.status)) : { kind: 'stopped-unconfirmed', status: stop.status };
      }
      return { kind: 'aborted', stop, last };
    }

    lastSendAt = now();
    const r = await poll();
    const alarm = anyAlarm(r);
    if (alarm !== null) return { kind: 'alarm', alarm, last };
    if (r.kind !== 'sent') {
      misses += 1;
      deps.onEvent?.({ kind: 'missed', misses, detail: said(r) });
      // A pressed Stop is always sent (#423 re-review): it goes out at the next boundary, even when
      // this miss would otherwise have been the one that gave up.
      if (misses >= deps.settings.missLimit && !deps.stopRequested()) return { kind: 'unreachable', last, misses };
      continue;
    }
    misses = 0;
    const p = readProgress(r.text);
    last = p;
    deps.onEvent?.({ kind: 'poll', progress: p });
    if (p.percent !== null) seenProgress = true;
    if (p.percent === 100 && p.state === 'Idle') return finish(p);
    if (seenProgress && p.percent === null && p.state === 'Idle') return finish(p);
    if (!seenProgress && now() - playSentAt >= deps.settings.noProgressMs) {
      // Nothing ran. A vacuum THIS run switched on goes off again — but only on a machine that
      // reads Idle: anything else is a machine doing something this watch cannot see. A program's
      // own words never executed, so there is nothing to switch either way. The antistatic this run
      // switched on goes off on the same Idle-only rule (#564).
      const vacuumOff =
        vacOwner === 'runner' && p.state === 'Idle' ? (await send(VACUUM_OFF)).kind === 'sent' : false;
      const antistaticOff =
        deps.antistatic === true && p.state === 'Idle' ? (await send(ANTISTATIC_OFF)).kind === 'sent' : undefined;
      return {
        kind: 'never-started',
        last,
        vacuumOff,
        vacuumOwner: vacOwner,
        ...(antistaticOff === undefined ? {} : { antistaticOff }),
        ...(span === undefined ? {} : { span }),
      };
    }
  }

  async function finish(at: Progress): Promise<RunOutcome> {
    // A runner-owned vacuum is switched off and homed here. A program-owned one turned itself off
    // in its last lines; this run only homes. The antistatic is always this run's (#564): the
    // program never carries `M331.4`/`M332.4`, so it is switched off here before the home.
    const off = vacOwner === 'runner' ? await send(VACUUM_OFF) : null;
    const antiOff = deps.antistatic === true ? await send(ANTISTATIC_OFF) : null;
    const home = await send('$H');
    return {
      kind: 'finished',
      last: at,
      vacuumOff: off !== null && off.kind === 'sent' && anyAlarm(off) === null,
      ...(antiOff === null ? {} : { antistaticOff: antiOff.kind === 'sent' && anyAlarm(antiOff) === null }),
      vacuumOwner: vacOwner,
      ...(span === undefined ? {} : { span }),
      homed: home.kind === 'sent' && anyAlarm(home) === null,
    };
  }
}

/** What a finished file left the vacuum doing, in the operator's words (#419 decision 4). */
function finishedVacuum(o: Extract<RunOutcome, { kind: 'finished' }>): string {
  if (o.vacuumOwner === 'job') {
    switch (o.span) {
      case 'whole':
      case 'last':
        return 'The program switched the vacuum off itself (its own M332); ';
      case 'first':
        return 'The vacuum stays on for the next program (the job turns it off at its last file); ';
      case 'middle':
        return 'The vacuum stays on for the next program (the job’s first file turned it on); ';
      case 'none':
        return 'This job runs without the vacuum; ';
      default:
        return 'The job owns the vacuum span; ';
    }
  }
  if (o.vacuumOwner === 'program') return 'The program switched the vacuum off itself (its own M332); ';
  return o.vacuumOff ? 'Vacuum off; ' : 'The vacuum-off (M332) was not confirmed — check it; ';
}

/** What a program that never started left the vacuum doing. */
function noStartVacuum(o: Extract<RunOutcome, { kind: 'never-started' }>): string {
  if (o.vacuumOwner === 'job') {
    if (o.span === 'middle' || o.span === 'last') {
      return 'The program never began; the vacuum is still on from the job’s earlier file — switch it off when you are at the machine.';
    }
    return 'The program never ran, so nothing was switched either way.';
  }
  if (o.vacuumOwner === 'program') {
    return 'The program owns the vacuum words and never ran, so nothing was switched either way.';
  }
  return o.vacuumOff
    ? 'The vacuum was switched off again.'
    : 'The machine did not read Idle, so the vacuum was left as it is — check the machine.';
}

/** The outcome in a sentence, for the panel. */
export function describeRun(o: RunOutcome): string {
  switch (o.kind) {
    case 'refused':
      return `Not started: ${o.reason}.`;
    case 'finished':
      return `Finished${o.last.elapsedS !== null ? ` in ${Math.round(o.last.elapsedS)} s` : ''}. ${finishedVacuum(o)}${
        o.homed ? 'homed' : 'the home ($H) was not confirmed — home it'
      }.`;
    case 'aborted':
      return o.stop.kind === 'stopped'
        ? `Stopped at line ${o.last.line ?? '?'}${o.stop.vacuumOff ? ', vacuum off' : ' — the vacuum-off was not confirmed'}${
            o.stop.antistaticOff === undefined
              ? ''
              : o.stop.antistaticOff
                ? ', antistatic off'
                : ' — the antistatic-off was not confirmed'
          }. Home the machine when the head is clear.`
        : `Stop was sent, but: ${'detail' in o.stop ? o.stop.detail : o.stop.kind}. The machine's red button is the emergency stop.`;
    case 'alarm':
      return `The controller said \`${o.alarm}\` — an alarm. Nothing further was sent; the physical stop is the stop.`;
    case 'unreachable':
      return `Silence is not stopped: ${o.misses} status polls in a row went unanswered. The job was NOT stopped from here and the vacuum was not switched off — the physical stop (the machine's button, the plug) is the stop.`;
    case 'never-started':
      return `No job progress ever appeared — nothing here was watching a job. ${noStartVacuum(o)}`;
    case 'stopped-unconfirmed':
      return 'Stop was pressed before the machine reported any progress, and it reads Idle — nothing shows whether the program ran, so nothing further was sent (no M332: the vacuum is still on; no home). Check the machine.';
  }
}

/** The run tunables from the shop's defaults (`run.*`) — the labelled fallbacks only with no service. */
export function runSettings(defaults: ShopDefaults | null): RunSettings {
  return {
    pollMs: Math.max(RUN_POLL_FLOOR_MS, readDefault(defaults, 'run.pollMs').value),
    noProgressMs: readDefault(defaults, 'run.noProgressMs').value,
    missLimit: readDefault(defaults, 'run.missLimit').value,
    statusTiming: statusPollTimingFrom(defaults),
    stop: stopSettings(defaults),
  };
}

