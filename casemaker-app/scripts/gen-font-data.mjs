// Regenerates src/engine/fonts/bundledFontData.ts from the TTFs in
// src/engine/fonts/files/. The fonts are embedded as base64 so the compiler can
// parse them synchronously in the browser, the geometry worker, vitest and the
// tsx sample exporter alike (no asset loader needed). Run: node scripts/gen-font-data.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'engine', 'fonts');
const files = [
  'Barlow-Regular.ttf',
  'Barlow-Bold.ttf',
  'IBMPlexMono-Regular.ttf',
  'IBMPlexMono-Bold.ttf',
  'IBMPlexSerif-Regular.ttf',
  'IBMPlexSerif-Bold.ttf',
];
let out =
  '// GENERATED by scripts/gen-font-data.mjs - do not edit. Fonts are SIL OFL 1.1; see NOTICE.\n' +
  'export const BUNDLED_FONT_DATA: Record<string, string> = {\n';
for (const f of files) {
  const b64 = readFileSync(join(root, 'files', f)).toString('base64');
  out += `  '${f.replace('.ttf', '')}': '${b64}',\n`;
}
out += '};\n';
writeFileSync(join(root, 'bundledFontData.ts'), out);
console.log('wrote', files.length, 'fonts,', (out.length / 1024).toFixed(0), 'KiB');
